def test_bad_history_and_immutable_events(ledger):
    e = next(e for e in ledger.events if e.key == "december")
    with pytest.raises(FrozenInstanceError):
        e.value = 999
    with pytest.raises(ResearchError, match="DUPLICATE_SOURCE_HISTORY"):
        EventLedger((*ledger.events, e))
    other = replace(e, provenance=replace(e.provenance, version="conflicting_version"), value=999)
    with pytest.raises(ResearchError, match="CONFLICTING_SAME_PRIORITY_HISTORY"):
        EventLedger((*ledger.events, other))
    with pytest.raises(ResearchError, match="MISSING_REVISION_PARENT"):
        EventLedger((replace(e, predecessor="missing"),))
    with pytest.raises(ResearchError, match="IMMUTABLE_LEDGER_REQUIRED"):
        EventLedger(list(ledger.events))


def test_in_memory_file_tampering():
    for pin in SOURCE_PINS:
        original = (sources.checkout_root() / pin[0]).read_bytes()
        verify_pin(original, pin)
        altered = original[:10] + bytes([original[10] ^ 1]) + original[11:]
        with pytest.raises(ResearchError, match="FIXTURE_PIN_MISMATCH"):
            verify_pin(b"fake original bytes", pin)
        with pytest.raises(ResearchError, match="FIXTURE_PIN_MISMATCH"):
            verify_pin(altered, pin)


def test_loader_pin_precedes_extraction(monkeypatch):
    monkeypatch.setattr(sources, "regular_bytes", lambda _: b"not original")
    with pytest.raises(ResearchError, match="FIXTURE_PIN_MISMATCH"):
        sources.load_pinned_synthetic_events()


def test_original_extraction_timestamp_link_controls():
    # Trusted-loader parser negatives only, never presented as safe public objects.
    original = json.loads((sources.checkout_root() / SOURCE_PINS[1][0]).read_bytes())
    bad = copy.deepcopy(original)
    proof = bad["sources"][2]["source"]["request"]["attempts"][0]["supplied"]["proof_candidate"]
    proof["timestamp"]["source_text"] = "2027-01-07T17:59:59"
    with pytest.raises(ResearchError, match="INVALID_ORIGINAL_TIMESTAMP"):
        sources._extract_notices(bad)
    bad = copy.deepcopy(original)
    proof = bad["sources"][2]["source"]["request"]["attempts"][0]["supplied"]["proof_candidate"]
    proof["timestamp"]["source_text"] = "2027-01-07T17:59:58+08:00"
    with pytest.raises(ResearchError, match="NOTICE_PUBLICATION_LINK"):
        sources._extract_notices(bad)
    bad = copy.deepcopy(original)
    bad["sources"].append(copy.deepcopy(bad["sources"][5]))
    with pytest.raises(ResearchError, match="DUPLICATE_REVISION_NOTICE"):
        sources._extract_notices(bad)


def test_future_poison_and_availability_contamination(ledger):
    # Test-only value-event mutation; no source-file writes and no alternative trusted loader.
    events = tuple(
        replace(e, value=987654321) if e.provenance.version == "PREP01-CV-D3" else e
        for e in ledger.events
    )
    poisoned = EventLedger(events)
    before = asof_view(ledger, CUTOFFS[2])
    assert before == asof_view(poisoned, CUTOFFS[2])
    assert features(asof_view(poisoned, CUTOFFS[3]))["december"].value == 987654321
    assert features(asof_view(ledger, CUTOFFS[3]))["december"].value == 90
    with pytest.raises(ResearchError, match="FUTURE_FEATURE_REFUSED"):
        replace(before, features=asof_view(ledger, CUTOFFS[3]).features)
    with pytest.raises(ResearchError, match="FEATURE_SET_CONTAMINATION"):
        replace(before, features=before.features[:-1])
    with pytest.raises(ResearchError, match="FEATURE_KEY"):
        Feature("future_label", "KNOWN", 1, "NONE", None)


