@pytest.fixture(scope="module")
def ledger():
    return load_pinned_synthetic_events()


def features(observation):
    return {f.key: f for f in observation.features}


def test_RC01_T01_original_before_at(ledger):
    dec = [e for e in ledger.events if e.key == "december"]
    assert [(e.provenance.publication, e.value) for e in dec] == [
        ("2027-01-07T17:59:59+08:00", 100),
        ("2027-01-07T18:00:00+08:00", 110),
        ("2027-01-29T18:00:01+08:00", 90),
    ]
    first = features(asof_view(ledger, "2027-01-07T18:00:00+08:00"))
    assert first["december"].value == first["foundation_a_december"].value == 100
    assert first["december"].provenance.version == "PREP01-CV-D1"
    assert first["december"].provenance.value_pointer == "/sources/2/raw/utf8#/statements/0/value"
    assert first["correction_1"].state == "ABSENT"
    assert first["foundation_b_december"].state == "ABSENT"


def test_RC01_T02_revision_isolation(ledger):
    historic = asof_view(ledger, CUTOFFS[0])
    expected = [
        (100, "PREP01-CV-D1"),
        (110, "PREP01-CV-D2"),
        (110, "PREP01-CV-D2"),
        (90, "PREP01-CV-D3"),
    ]
    for cutoff, (amount, version) in zip(CUTOFFS, expected, strict=True):
        f = features(asof_view(ledger, cutoff))["december"]
        assert (f.value, f.provenance.version) == (amount, version)
    assert features(historic)["december"].value == 100
    assert historic == asof_view(ledger, CUTOFFS[0])
    assert len([e for e in ledger.events if e.key == "december"]) == 3


def test_RC01_T03_equal_clock_distinct_origins(ledger):
    f = features(asof_view(ledger, CUTOFFS[1]))
    left, right = f["december"].provenance, f["correction_1"].provenance
    assert left.publication == right.publication == "2027-01-07T18:00:00+08:00"
    assert (left.record, right.record) == ("PREP01-A-D2", "PREP01-A-N12")
    assert left.content_sha256 != right.content_sha256
    assert left.value_pointer != right.value_pointer
    old = features(asof_view(ledger, CUTOFFS[0]))
    assert (old["october"].value, old["november"].value) == (17, 23)
    assert old["october"].provenance.publication == "2026-11-05T12:00:00+08:00"
    assert old["november"].provenance.publication == "2026-12-05T12:00:00+08:00"


def test_RC02_T01_independent_boundary_controls(ledger):
    # Literal expectations, neither generated by eligibility nor by fixture oracle fields.
    assert instant("2027-01-07T17:59:59+08:00") < instant(CUTOFFS[0])
    assert instant("2027-01-07T18:00:00+08:00") == instant(CUTOFFS[0])
    assert instant(CUTOFFS[2]) < instant("2027-01-29T18:00:01+08:00") < instant(CUTOFFS[3])
    for index, amount, relation in [
        (0, 100, "ABSENT"),
        (1, 110, "ABSENT"),
        (2, 110, "ABSENT"),
        (3, 90, "KNOWN"),
    ]:
        view = features(asof_view(ledger, CUTOFFS[index]))
        assert view["december"].value == amount
        assert view["correction_2"].state == relation
        assert view["correction_1"].state == ("ABSENT" if index == 0 else "KNOWN")


def test_RC02_T03_statuses_no_zero_fill(ledger):
    f = features(asof_view(ledger, CUTOFFS[0]))
    assert [
        (f[k].state, f[k].value)
        for k in ["provider", "restricted_fields", "evaluation", "unprovided_feature"]
    ] == [("UNKNOWN", None), ("WITHHELD", None), ("NOT_EVALUATED", None), ("ABSENT", None)]
    assert (
        f["provider"].provenance.value_pointer
        == "/sources/0/source/request/content/provider_ref/type"
    )
    for key in ["provider", "restricted_fields", "evaluation", "unprovided_feature"]:
        with pytest.raises(ResearchError, match="CONTAMINATION"):
            replace(f[key], value=0)
    with pytest.raises(ResearchError, match="POLICY_STATE_CONTAMINATION"):
        replace(f["restricted_fields"], state="KNOWN", value=1)


